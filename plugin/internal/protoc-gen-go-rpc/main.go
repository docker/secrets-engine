// Command protoc-gen-go-rpc generates the clients and handlers of the
// services in a proto file. The code builds on
// github.com/docker/secrets-engine/plugin/rpc, which serves unary RPCs only.
//
// For foo/v1/api.proto with the Go package name foov1, the command writes
// foo/v1/foov1rpc/api.rpc.go. buf generate runs it: see buf.gen.yaml.
package main

import (
	"flag"
	"fmt"
	"path"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const rpcPackage = protogen.GoImportPath("github.com/docker/secrets-engine/plugin/rpc")

var (
	contextContext = protogen.GoImportPath("context").Ident("Context")
	errorsNew      = protogen.GoImportPath("errors").Ident("New")
	httpHandler    = protogen.GoImportPath("net/http").Ident("Handler")
	protoMessage   = protogen.GoImportPath("google.golang.org/protobuf/proto").Ident("Message")
)

func main() {
	opts, clientModule := options()
	opts.Run(func(plugin *protogen.Plugin) error {
		return generate(plugin, *clientModule)
	})
}

func options() (protogen.Options, *string) {
	var flags flag.FlagSet
	clientModule := flags.String("client_module", "", "write, for the proto files whose Go package is in this module, only clients that send requests through a function")
	return protogen.Options{ParamFunc: flags.Set}, clientModule
}

func generate(plugin *protogen.Plugin, clientModule string) error {
	plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
	plugin.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_PROTO2
	plugin.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_2023
	for _, file := range plugin.Files {
		if !file.Generate || len(file.Services) == 0 {
			continue
		}
		if clientModule != "" && !inModule(file.GoImportPath, clientModule) {
			continue
		}
		if err := generateFile(plugin, file, clientModule != ""); err != nil {
			return err
		}
	}
	return nil
}

func inModule(pkg protogen.GoImportPath, module string) bool {
	return string(pkg) == module || strings.HasPrefix(string(pkg), module+"/")
}

func generateFile(plugin *protogen.Plugin, file *protogen.File, clientOnly bool) error {
	for _, service := range file.Services {
		for _, method := range service.Methods {
			if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
				return fmt.Errorf("%s: %s is a streaming RPC: only unary RPCs are supported", file.Desc.Path(), method.Desc.FullName())
			}
		}
	}

	pkg := string(file.GoPackageName) + "rpc"
	dir, base := path.Split(file.GeneratedFilenamePrefix)
	g := plugin.NewGeneratedFile(dir+pkg+"/"+base+".rpc.go", protogen.GoImportPath(path.Join(string(file.GoImportPath), pkg)))
	g.P("// Code generated by protoc-gen-go-rpc. DO NOT EDIT.")
	g.P("//")
	g.P("// Source: ", file.Desc.Path())
	g.P()
	g.P("package ", pkg)
	g.P()
	if !clientOnly {
		g.P("const (")
		for _, service := range file.Services {
			g.P("// ", service.GoName, "Name is the fully-qualified name of the ", service.Desc.Name(), " service.")
			g.P(service.GoName, "Name = ", strconv.Quote(string(service.Desc.FullName())))
		}
		g.P(")")
		g.P()
	}
	g.P("const (")
	for _, service := range file.Services {
		for _, method := range service.Methods {
			g.P("// ", procedure(method), " is the fully-qualified name of the ", service.Desc.Name(), "'s ", method.Desc.Name(), " RPC.")
			g.P(procedure(method), " = ", strconv.Quote(fmt.Sprintf("/%s/%s", service.Desc.FullName(), method.Desc.Name())))
		}
	}
	g.P(")")
	for _, service := range file.Services {
		generateClient(g, service, clientOnly)
		if !clientOnly {
			generateHandler(g, service)
		}
	}
	return nil
}

func generateClient(g *protogen.GeneratedFile, service *protogen.Service, clientOnly bool) {
	name := service.GoName + "Client"
	impl := strings.ToLower(name[:1]) + name[1:]

	g.P()
	g.P("// ", name, " is a client for the ", service.Desc.FullName(), " service.")
	g.P("type ", name, " interface {")
	for _, method := range service.Methods {
		g.P(method.Comments.Leading, method.GoName, "(", contextContext, ", *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error)")
	}
	g.P("}")
	g.P()
	if clientOnly {
		call := "func(ctx " + g.QualifiedGoIdent(contextContext) + ", procedure string, req, res " + g.QualifiedGoIdent(protoMessage) + ") error"
		g.P("// New", name, " constructs a client for the ", service.Desc.FullName(), " service that sends each request through call.")
		g.P("func New", name, "(call ", call, ") ", name, " {")
		g.P("return &", impl, "{call}")
		g.P("}")
		g.P()
		g.P("type ", impl, " struct {")
		g.P("call ", call)
		g.P("}")
		for _, method := range service.Methods {
			g.P()
			g.P("func (c *", impl, ") ", method.GoName, "(ctx ", contextContext, ", req *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
			g.P("res := &", method.Output.GoIdent, "{}")
			g.P("if err := c.call(ctx, ", procedure(method), ", req, res); err != nil {")
			g.P("return nil, err")
			g.P("}")
			g.P("return res, nil")
			g.P("}")
		}
		return
	}
	g.P("// New", name, " constructs a client for the ", service.Desc.FullName(), ` service at baseURL, for example "http://unix".`)
	g.P("func New", name, "(httpClient ", rpcPackage.Ident("HTTPClient"), ", baseURL string, opts ...", rpcPackage.Ident("ClientOption"), ") ", name, " {")
	g.P("return &", impl, "{", rpcPackage.Ident("NewClient"), "(httpClient, baseURL, opts...)}")
	g.P("}")
	g.P()
	g.P("type ", impl, " struct {")
	g.P("client *", rpcPackage.Ident("Client"))
	g.P("}")
	for _, method := range service.Methods {
		g.P()
		g.P("func (c *", impl, ") ", method.GoName, "(ctx ", contextContext, ", req *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
		g.P("return ", rpcPackage.Ident("CallUnary"), "[", method.Output.GoIdent, "](ctx, c.client, ", procedure(method), ", req)")
		g.P("}")
	}
}

func generateHandler(g *protogen.GeneratedFile, service *protogen.Service) {
	name := service.GoName + "Handler"

	g.P()
	g.P("// ", name, " is an implementation of the ", service.Desc.FullName(), " service.")
	g.P("type ", name, " interface {")
	for _, method := range service.Methods {
		g.P(method.Comments.Leading, method.GoName, "(", contextContext, ", *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error)")
	}
	g.P("}")
	g.P()
	g.P("// New", name, " builds an HTTP handler from the service implementation.")
	g.P("// It returns the path on which to mount the handler, and the handler itself.")
	g.P("func New", name, "(svc ", name, ", opts ...", rpcPackage.Ident("HandlerOption"), ") (string, ", httpHandler, ") {")
	g.P("return ", rpcPackage.Ident("NewServiceHandler"), "(", service.GoName, "Name,")
	for _, method := range service.Methods {
		g.P(rpcPackage.Ident("NewUnaryHandler"), "(", procedure(method), ", svc.", method.GoName, ", opts...),")
	}
	g.P(")")
	g.P("}")
	g.P()
	g.P("// Unimplemented", name, " returns CodeUnimplemented from all methods.")
	g.P("type Unimplemented", name, " struct{}")
	for _, method := range service.Methods {
		g.P()
		g.P("func (Unimplemented", name, ") ", method.GoName, "(", contextContext, ", *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
		g.P("return nil, ", rpcPackage.Ident("NewError"), "(", rpcPackage.Ident("CodeUnimplemented"), ", ", errorsNew, "(", strconv.Quote(string(method.Desc.FullName())+" is not implemented"), "))")
		g.P("}")
	}
}

func procedure(method *protogen.Method) string {
	return method.Parent.GoName + method.GoName + "Procedure"
}
